#!/usr/bin/env python3
"""Exact structural replay; see README.md for mathematical proof dependencies.

No historical tableau or transportation count is regenerated by the gap-three
or transport modes. The two-row mode evaluates its complete character formula
with a separate bounded integer product recurrence.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
import time

from exact import (Q, CheckError, need, integer, rational, trim, plus, minus,
                   scale, times, shift, evaluate, lagrange, newton,
                   binomial_polynomial)
import gap_algebra

HERE = Path(__file__).resolve().parent


def decode(path):
    def unique(pairs):
        out = {}
        for key, value in pairs:
            need(key not in out, f"Duplicate JSON key: {key}")
            out[key] = value
        return out
    return json.loads(Path(path).read_text(), object_pairs_hook=unique)


def authenticate(module, data_dir):
    manifest = decode(HERE / "SOURCE-MAP.json")
    seen = set()
    for row in manifest["files"]:
        if module != "all" and module not in row["modules"]:
            continue
        name = row["path"]
        need(name not in seen, "Duplicate manifest file identity")
        seen.add(name)
        path = data_dir / Path(name).name if name.startswith("data/") else HERE / name
        raw = path.read_bytes()
        need(len(raw) == row["bytes"] and hashlib.sha256(raw).hexdigest() == row["sha256"],
             f"Source or input bytes differ: {name}")
    return len(seen)


def suffix_lift(weights, slope):
    weights = list(weights)
    need(type(slope) is int and slope in (2, 3), "Only slopes two and three are packaged")
    need(len(weights) >= (5 if slope == 2 else 6), "Too few positive weights for the theorem")
    need(all(type(w) is int and w > 0 for w in weights), "Weights must be positive exact integers")
    lam = [sum(weights[i:]) for i in range(len(weights))]
    return {"lambda_outer": lam, "mu": lam[1:], "nu": [sum(weights) - slope, slope]}


def two_row_polynomial(weights, slope):
    suffix_lift(weights, slope)
    d = len(weights) - 2
    u, v = weights.count(1), weights.count(2)
    if slope == 2:
        return minus(binomial_polynomial(2, d, d), scale(binomial_polynomial(1, d - 1, d), u))
    return plus(minus(minus(binomial_polynomial(3, d, d),
                            scale(binomial_polynomial(2, d - 1, d), u)),
                       scale(binomial_polynomial(1, d - 1, d), v)),
                scale(binomial_polynomial(1, d - 2, d), u * (u - 1) // 2))


def direct_character_count(weights, slope, t):
    """Complete truncated product, then the two-variable Schur difference."""
    suffix_lift(weights, slope)
    need(type(t) is int and t >= 0, "Stretch must be a nonnegative exact integer")
    target = slope * t
    row = [1] + [0] * target
    for w in weights:
        following = [0] * (target + 1)
        window = 0
        cap = w * t
        for k in range(target + 1):
            window += row[k]
            if k > cap:
                window -= row[k - cap - 1]
            following[k] = window
        row = following
    return row[target] - (row[target - 1] if target else 0)


def check_two_row():
    finite = []
    for d in range(4, 21):
        p = two_row_polynomial([1] * (d + 2), 3)
        need(p[0] == 1, "Uniform slope-three constant differs")
        if d == 4:
            need(p == [Q(1), Q(2), Q(3, 2), Q(1, 2)], "Uniform rank-six degree drop differs")
        else:
            need(len(p) == d + 1 and all(c > 0 for c in p), "Uniform finite proof case is not positive")
        n = d + 2
        need(evaluate(p, 1) == Q(n * (n - 1) * (n - 5), 6), "Uniform grade-one identity differs")
        finite.append({"d": d, "actual_degree": len(p) - 1,
                       "ambient_coefficients": list(map(str, p + [Q(0)] * (d + 1 - len(p))))})
    profiles = sites = 0
    for slope in (2, 3):
        for n in range(5 if slope == 2 else 6, 11):
            for u in range(n + 1):
                for v in (range(n - u + 1) if slope == 3 else [n - u]):
                    weights = [1] * u + [2] * v + [3] * (n - u - v)
                    p = two_row_polynomial(weights, slope)
                    need(all(c > 0 for c in p), "Bounded profile coefficient sign differs")
                    for t in range(4):
                        need(evaluate(p, t) == direct_character_count(weights, slope, t),
                             "Whole character product disagrees with polynomial formula")
                        sites += 1
                    profiles += 1
    for slope, weights in ((2, [1, 7, 2, 4, 1]), (3, [1, 9, 2, 3, 5, 1])):
        p = two_row_polynomial(weights, slope)
        need(p == two_row_polynomial(list(reversed(weights)), slope), "Weight ordering changes the formula")
        for t in range(4):
            need(evaluate(p, t) == direct_character_count(weights, slope, t), "Unequal-weight product differs")
            sites += 1
        profiles += 1
    return {"status": "EXACT_FINITE_PROOF_CASES_AND_BOUNDED_CHARACTER_CHECKS_PASS",
            "finite_uniform_cases": finite, "finite_ambient_coefficient_occurrences": 221,
            "bounded_profiles": profiles, "bounded_character_sites": sites,
            "scope": "All-rank positivity uses the complete proofs, including the analytic d >= 21 bound; bounded profiles are checks only."}


def exact_rows(rows, key, expected):
    need(type(rows) is list and len(rows) == len(expected), "Missing or extra record")
    out = {}
    for row in rows:
        identity = key(row)
        need(identity in expected and identity not in out, "Missing, duplicate or extra literal identity")
        out[identity] = row
    need(set(out) == set(expected), "Incomplete literal identity set")
    return out


def check_gap(data):
    need(data["schema"] == "gap-three-historical-counts-v1", "Wrong gap-three data schema")
    parents = exact_rows(data["parents"], lambda r: r["id"], set(gap_algebra.PARENTS))
    counts = {}
    for name, (x, y) in gap_algebra.PARENTS.items():
        row = parents[name]
        need(type(row["x"]) is int and type(row["y"]) is int and (row["x"], row["y"]) == (x, y),
             "Wrong gap-three parent parameters")
        nodes = exact_rows(row["positive_counts"], lambda r: integer(r["t"]), set(range(1, 11)))
        for t, node in nodes.items():
            counts[f"{name}:t{t}"] = integer(node["value"])
            need(counts[f"{name}:t{t}"] > 0, "Historical complete count is not positive")
    polynomials = gap_algebra.reconstruct(counts)
    for name, row in parents.items():
        p = polynomials[name]
        need(len(p) == 11 and p == list(map(rational, row["coefficients"])), "Complete parent coefficients differ")
        for t in (9, 10):
            need(evaluate(p, t) == counts[f"{name}:t{t}"], "Unused historical hold rejects reconstruction")
    need(set(data["expected_vectors"]) == set(polynomials), "Missing or extra complete vector identity")
    for name, p in polynomials.items():
        need(p == list(map(rational, data["expected_vectors"][name])), "Historical full vector differs")
    algebra = gap_algebra.algebra(polynomials, data["factor_arrays"])
    negatives = gap_algebra.negative_observations({"W0": polynomials["W0"]})
    need([(r["degree"], r["coefficient"]) for r in negatives] ==
         [(1, "-1/7"), (2, "-101/210"), (3, "-2741/5040"), (4, "-151/2520")],
         "The complete negative auxiliary correction was changed")
    return {"status": "EXACT_ALGEBRA_FROM_HISTORICAL_COUNTS_PASS", "historical_positive_sites": 40,
            "positive_determining_sites": 32, "unused_historical_sites": 8,
            "fresh_tableau_counts": 0, "vectors": {k: list(map(str, p)) for k, p in polynomials.items()},
            "algebra": algebra,
            "scope": "Entire quadrant/cone count identities and strict-GT degree/interior premises are analytic dependencies, not consequences of interpolation."}


def transport_bare(h):
    return {"lambda_outer": [27+h, 22+h, 18+h, 17+h, 13, 10, 8, 6, 4, 2],
            "mu": [17+h, 17+h, 17+h, 13, 10, 8, 6, 4, 2], "nu": [17+h, 10, 5, 1]}


def check_transport(data):
    need(data["schema"] == "transport-historical-counts-v1", "Wrong transport data schema")
    rows = exact_rows(data["parents"], lambda r: integer(r["h"]), set(range(7)))
    polynomials = []
    for h in range(7):
        row = rows[h]
        need(row["id"] == f"TF-{h}" and row["bare"] == transport_bare(h), "Wrong complete transport parent identity")
        nodes = exact_rows(row["counts"], lambda r: integer(r["t"]), set(range(15)))
        values = {t: integer(node["value"]) for t, node in nodes.items()}
        need(values[0] == 1 and all(v > 0 for v in values.values()), "Wrong zero grade or positive count")
        xs = list(range(-6, 13))
        ys = [0] * 6 + [values[t] for t in range(13)]
        p = lagrange(xs, ys)
        need(p == newton(xs, ys), "Lagrange and Newton reconstruction differ")
        need(len(p) == 19 and p == list(map(rational, row["coefficients"])) and all(c > 0 for c in p),
             "Complete endpoint degree, coefficients or strict positivity differ")
        for t in (13, 14):
            need(evaluate(p, t) == values[t], "Unused historical transport hold rejects reconstruction")
        witness = row["strict_grade_seven_witness"]
        need(type(witness) is list and len(witness) == 4 and all(type(r) is list and len(r) == 7 for r in witness),
             "Incomplete grade-seven interior witness")
        need(all(type(x) is int and x > 0 for r in witness for x in r), "Interior witness is not strictly positive integer")
        need([sum(r) for r in witness] == [7 * x for x in (7+h, 5, 4, 1)], "Interior witness row margin differs")
        need([sum(witness[i][j] for i in range(4)) for j in range(7)] == [7 * x for x in (4+h, 3, 2, 2, 2, 2, 2)],
             "Interior witness column margin differs")
        polynomials.append(p)
    differences = [minus(b, a) for a, b in zip(polynomials, polynomials[1:])]
    need(all(len(p) == 19 and p[0] == 0 and all(c > 0 for c in p[1:]) for p in differences),
         "Complete cap-release difference is not strictly positive off its constant")
    need(differences[-1] == binomial_polynomial(1, 17, 18), "Final shell differs from binomial(t+17,18)")
    first = [p[1] for p in polynomials]
    need(first == list(map(Q, ["5279/360", "1085/72", "5521/360", "1117/72", "1127/72", "1133/72", "379/24"])),
         "Transport linear endpoint list differs")
    return {"status": "EXACT_ALGEBRA_FROM_HISTORICAL_COUNTS_PASS", "historical_positive_sites": 98,
            "positive_determining_sites": 84, "unused_historical_sites": 14, "grade_zero_constants": 7,
            "fresh_transportation_counts": 0, "endpoint_coefficients": [list(map(str, p)) for p in polynomials],
            "difference_coefficients": [list(map(str, p)) for p in differences],
            "ordinary_endpoint_entries": 133, "positive_difference_entries": 108,
            "linear_endpoints": list(map(str, first)),
            "scope": "All integer h >= 0 uses the complete count identity and analytic h >= 6 stabilization. Middle cone coefficients at noninteger v/u remain open."}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--module", choices=("all", "two-row", "gap-three", "transport"), default="all")
    parser.add_argument("--data-dir", type=Path, default=HERE / "data")
    args = parser.parse_args(argv)
    started = time.monotonic()
    try:
        files = authenticate(args.module, args.data_dir)
        result = {"schema": "structural-standalone-replay-v1", "authenticated_files": files, "modules": {}}
        if args.module in ("all", "two-row"):
            result["modules"]["two-row"] = check_two_row()
        if args.module in ("all", "gap-three"):
            result["modules"]["gap-three"] = check_gap(decode(args.data_dir / "gap-three.json"))
        if args.module in ("all", "transport"):
            result["modules"]["transport"] = check_transport(decode(args.data_dir / "transport.json"))
        result["status"] = "PASS"
        result["elapsed_seconds"] = time.monotonic() - started
        print(json.dumps(result, indent=2, sort_keys=True))
        return 0
    except (CheckError, OSError, KeyError, TypeError, ValueError, ZeroDivisionError) as error:
        print(json.dumps({"status": "FAIL", "error": f"{type(error).__name__}: {error}",
                          "elapsed_seconds": time.monotonic() - started}), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
